struct WebEndpoint {
  std::string url;
  std::string host;
};

// общий fetch_web чтобы не дублировать запросы с tech/headers
std::vector<WebEndpoint> endpoints(ModuleContext& ctx) {
  std::vector<WebEndpoint> out;
  std::set<std::string> seen_hosts;
  for (const auto& t : ctx.cfg.targets) {
    if (t.scheme == "http" || t.scheme == "https") {
      std::string url = t.scheme + "://" + t.host;
      if (t.port > 0 &&
          !((t.scheme == "http" && t.port == 80) ||
            (t.scheme == "https" && t.port == 443)))
        url += ":" + std::to_string(t.port);
      url += "/";
      if (!seen_hosts.count(t.host)) {
        seen_hosts.insert(t.host);
        out.push_back({url, t.host});
      }
      continue;
    }
    const HostResult* hr = ctx.result.find_host(t.host);
    if (!hr) continue;
    struct PM {
      uint16_t port;
      const char* scheme;
    };
    static const PM kWebPorts[] = {{80, "http"},    {443, "https"},
                                   {8080, "http"},  {8443, "https"},
                                   {8000, "http"},  {8008, "http"},
                                   {8888, "http"},  {9443, "https"}};
    for (const auto& wp : kWebPorts) {
      const PortInfo* pi = hr->port(wp.port);
      if (!pi || !pi->open) continue;
      std::string url = std::string(wp.scheme) + "://" + t.host;
      if (wp.port != 80 && wp.port != 443)
        url += ":" + std::to_string(wp.port);
      url += "/";
      std::string key = t.host + ":" + std::to_string(wp.port);
      if (!seen_hosts.count(key)) {
        seen_hosts.insert(key);
        out.push_back({url, t.host});
      }
    }
  }
  return out;
}

void note_visibility(HostResult& hr, const std::string& level,
                     const std::string& note) {
  if (hr.scan_visibility.empty() || hr.scan_visibility == "full")
    hr.scan_visibility = level;
  bool dup = false;
  for (const auto& n : hr.visibility_notes)
    if (n == note) dup = true;
  if (!dup) hr.visibility_notes.push_back(note);
}

class WafModule : public IModule {
 public:
  std::string name() const override { return "waf"; }
  std::string description() const override {
    return "WAF / anti-bot / rate-limiter / geo-block detection with an honest "
           "scan-visibility assessment (what the scanner could actually see)";
  }
  Maturity maturity() const override { return Maturity::Preview; }
  std::vector<std::string> depends() const override { return {"tech"}; }

  bool run(ModuleContext& ctx) override {
    auto eps = endpoints(ctx);
    if (eps.empty()) return true;
    ctx.pstage("waf", "assessing blockers", eps.size());

    for (const auto& ep : eps) {
      ctx.ptick();
      HostResult& hr = ctx.result.ensure_host(ep.host, false);

      // 1) базовая страница
      HttpOptions opt;
      opt.user_agent = ctx.cfg.user_agent;
      WebResult& base = ctx.fetch_web(ep.url, opt);
      if (!base.fetched) {
        if (base.error.find("timed out") == std::string::npos &&
            !base.error.empty()) {
          note_visibility(hr, "blocked",
                          "root page fetch failed: " + base.error);
        }
        continue;
      }

      // 2) пассивные подсказки из заголовков
      if (const char* vendor = header_waf_hint(base.headers); vendor && *vendor) {
        Finding f;
        f.severity = Severity::Info;
        f.module = "waf";
        f.host = ep.host;
        f.location = ep.url;
        f.title = std::string("Edge protection detected: ") + vendor;
        f.detail =
            "Response headers identify an edge service in front of the "
            "application. Origin-server headers and technologies observed in "
            "this report may have been added, changed or stripped by the edge, "
            "and some paths may be filtered before reaching the origin.\n"
            "PROXY/CDN DETECTED: " + std::string(vendor) + "\n"
            "EDGE NETWORK: " + std::string(vendor) + "\n"
            "EDGE IP: the address(es) mikto resolved for this host belong to "
            "the edge network, not to the application server\n"
            "ORIGIN STATUS: not publicly confirmed — any origin address "
            "would be a hypothesis, and mikto deliberately does not probe "
            "behind the edge, resolve hidden origins or attempt any "
            "CDN/WAF bypass (ethics policy)";
        f.recommendation =
            "Factor the edge layer into interpretation of this report; verify "
            "origin-side findings directly against the origin when possible. "
            "Only the infrastructure owner can fully confirm what the edge "
            "hides.";
        f.evidence = std::string("vendor: ") + vendor;
        ctx.result.add_finding(std::move(f));
      }

      // 3) странные статусы базы
      if (base.status == 429) {
        note_visibility(hr, "degraded",
                        "HTTP 429 (rate limited) on the baseline request");
        Finding f;
        f.severity = Severity::Info;
        f.module = "waf";
        f.host = ep.host;
        f.location = ep.url;
        f.title = "Rate limiting observed (HTTP 429)";
        f.detail =
            "The server already throttles the baseline request. mikto "
            "self-paces all further requests, but some checks may receive "
            "incomplete responses under an active limiter.";
        f.recommendation =
            "Re-run with a lower --rate if findings look sparse, or add an "
            "NVD API key to reduce external lookups.";
        ctx.result.add_finding(std::move(f));
      } else if (base.status == 403) {
        if (looks_like_geo_block(base.body)) {
          note_visibility(hr, "degraded", "geo/region block on baseline page");
          Finding f;
          f.severity = Severity::Info;
          f.module = "waf";
          f.host = ep.host;
          f.location = ep.url;
          f.title = "Geo/region restriction detected";
          f.detail =
              "The baseline page answers 403 with a region-restriction page. "
              "The scan observes the target from one network location only; "
              "content and behaviour may differ for other regions.";
          f.recommendation =
              "If the target is yours, confirm the geo policy matches your "
              "asset documentation.";
          ctx.result.add_finding(std::move(f));
        } else if (classify_antibot_challenge(base.body) &&
                   *classify_antibot_challenge(base.body)) {
          note_visibility(hr, "blocked", "anti-bot challenge on baseline page");
        } else if (classify_block_page(base.body, base.status) &&
                   *classify_block_page(base.body, base.status)) {
          note_visibility(hr, "degraded", "block page on baseline request");
        }
      }

      // 4) один безобидный проб
      std::string probe_url = ep.url + "?id=1+AND+1%3D1";
      WebResult& probe = ctx.fetch_web(probe_url, opt);
      if (probe.fetched) {
        if (probe.status != base.status) {
          if (const char* vendor = classify_block_page(probe.body, probe.status);
              vendor && *vendor) {
            note_visibility(hr, "degraded",
                            std::string("WAF blocked the probe request (") +
                                vendor + ")");
            Finding f;
            f.severity = Severity::Info;
            f.module = "waf";
            f.host = ep.host;
            f.location = probe_url;
            f.title = std::string("WAF is actively filtering requests (") +
                      vendor + ")";
            f.detail =
                "A request with an injection-looking query string was answered "
                "with a block page while the baseline page loaded normally. "
                "That is the WAF working as intended. mikto does not attempt "
                "to bypass it; results that depend on request content may be "
                "incomplete behind the filter.";
            f.recommendation =
                "Treat this as a positive control for the WAF; confirm the "
                "rule set also covers the endpoints that matter.";
            f.evidence = "probe status " + std::to_string(probe.status) +
                         " vs baseline " + std::to_string(base.status);
            ctx.result.add_finding(std::move(f));
          } else if (probe.status == 429) {
            note_visibility(hr, "degraded", "rate limiter answered the probe");
          }
        }
        if (const char* ch = classify_antibot_challenge(probe.body); ch && *ch) {
          note_visibility(hr, "degraded",
                          std::string("anti-bot challenge served (") + ch + ")");
          Finding f;
          f.severity = Severity::Info;
          f.module = "waf";
          f.host = ep.host;
          f.location = probe_url;
          f.title = std::string("Anti-bot challenge detected (") + ch + ")";
          f.detail =
              "The application answers automated requests with a browser "
              "challenge. Non-browser checks (DNS, ports, TLS) ran normally, "
              "but page-content checks (headers beyond the first response, "
              "secrets, paths) see the challenge instead of real content and "
              "may be incomplete.";
          f.recommendation =
              "For a complete content audit, run checks from an allowlisted "
              "workstation or use the challenge cookie from a manual session.";
          ctx.result.add_finding(std::move(f));
        }
      }

      // 5) свип видимости по всем страницам хоста
      for (const auto& w : ctx.result.web) {
        if (w.url.find("://" + ep.host) == std::string::npos &&
            w.url.find("//" + ep.host) == std::string::npos)
          continue;
        if (!w.fetched) continue;
        if (w.status == 429)
          note_visibility(hr, "degraded", "HTTP 429 observed during the scan");
        if (w.status == 403 &&
            classify_antibot_challenge(w.body) &&
            *classify_antibot_challenge(w.body))
          note_visibility(hr, "degraded", "anti-bot challenge observed");
      }

      if (hr.scan_visibility.empty()) hr.scan_visibility = "full";
    }
    return true;
  }
};

