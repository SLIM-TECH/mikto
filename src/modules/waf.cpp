const char* classify_block_page(const std::string& body, long status) {
  // на прочих статусах только уникальные сигнатуры вендора
  bool reject = (status == 403 || status == 406 || status == 418 ||
                 status == 429 || status == 501 || status == 503);
  std::string lb = to_lower(body);
  auto has = [&](const char* s) { return lb.find(s) != std::string::npos; };

  if (has("incapsula incident id") || has("_incapsula_resource"))
    return "Imperva/Incapsula";
  if (has("sucuri website firewall") || has("sucuri_cloudproxy_uuid") ||
      has("access denied - sucuri"))
    return "Sucuri";
  if (has("attention required! | cloudflare") || has("cf-error-details") ||
      has("cdn-cgi/challenge-platform") || has("1020 access denied"))
    return "Cloudflare";
  if (!reject) return "";
  if (has("datadome"))
    return "DataDome";
  if (has("perimeterx") || has("px-captcha") || has("human verification"))
    return "PerimeterX/HUMAN";
  if (has("mod_security") || has("modsecurity") ||
      (status == 406 && has("not acceptable")))
    return "ModSecurity";
  if (has("kasada") || has("x-kasada"))
    return "Kasada";
  if (has("ddos-guard"))
    return "DDoS-Guard";
  if (has("qrator"))
    return "Qrator";
  if (has("reblaze"))
    return "Reblaze";
  if (has("wallarm"))
    return "Wallarm";
  if (has("the requested url was rejected") || has("bigipserver") ||
      has("f5 big-ip"))
    return "F5/BIG-IP";
  if (has("error: the request could not be satisfied") ||
      (status == 403 && has("generated by cloudfront")))
    return "AWS CloudFront";
  // акамай последним, слишком общий
  if (status == 403 &&
      (has("support id") || has("akamai-ref") ||
       (has("access denied") && has("reference #"))))
    return "Akamai";
  return "";
}

const char* classify_antibot_challenge(const std::string& body) {
  std::string lb = to_lower(body);
  auto has = [&](const char* s) { return lb.find(s) != std::string::npos; };
  if (has("just a moment") && has("cloudflare")) return "Cloudflare";
  if (has("challenge-platform") || has("__cf_chl") ||
      has("cf_chl_opt"))
    return "Cloudflare";
  if (has("checking your browser") || has("checking if the site connection is secure"))
    return "Cloudflare";
  if (has("datadome") && has("captcha")) return "DataDome";
  if (has("px-captcha") || has("perimeterx")) return "PerimeterX/HUMAN";
  if (has("kasada")) return "Kasada";
  if (has("queue-it")) return "Queue-it";
  if (has("ddos protection by") || has("ddos-guard")) return "DDoS-Guard";
  if (has("please verify you are a human")) return "captcha wall";
  if (has("enable javascript and cookies to continue")) return "JS challenge";
  return "";
}

const char* header_waf_hint(
    const std::vector<std::pair<std::string, std::string>>& headers) {
  for (const auto& [name, value] : headers) {
    std::string ln = to_lower(name);
    std::string lv = to_lower(value);
    if (ln == "x-sucuri-id" || ln == "x-sucuri-cache") return "Sucuri";
    if (ln == "x-iinfo") return "Imperva/Incapsula";
    if (ln == "x-cdn" && lv.find("incapsula") != std::string::npos)
      return "Imperva/Incapsula";
    if (ln == "server" && lv.find("cloudflare") != std::string::npos)
      return "Cloudflare";
    if (ln == "server" && lv.find("ddos-guard") != std::string::npos)
      return "DDoS-Guard";
    if (ln == "server" && lv.find("cloudfront") != std::string::npos)
      return "AWS CloudFront";
    if (ln == "x-akamai-transformed" ||
        (ln == "server" && lv.find("akamai") != std::string::npos))
      return "Akamai";
    if (ln == "server" && lv.find("datadome") != std::string::npos)
      return "DataDome";
    if (ln == "x-arb" || ln == "x-reblaze-ref-id") return "Reblaze";
    if (ln == "x-fastly-request-id" ||
        (ln == "x-served-by" && lv.find("cache-") == 0))
      return "Fastly (CDN)";
    if (ln == "x-vercel-id") return "Vercel (CDN)";
    if (ln == "x-amz-cf-id") return "AWS CloudFront";
    if (ln == "x-guploader-uploadid") return "Google (CDN)";
    if (ln == "x-protected-by" || ln == "x-waf-status" || ln == "x-hw-error")
      return "WAF (header)";
    if (ln == "set-cookie") {
      if (lv.find("__cf_bm=") != std::string::npos ||
          lv.find("cf_clearance=") != std::string::npos)
        return "Cloudflare";
      if (lv.find("ak_bmsc=") != std::string::npos ||
          lv.find("bm_sv=") != std::string::npos)
        return "Akamai";
      if (lv.find("_incap_ses") != std::string::npos ||
          lv.find("visid_incap") != std::string::npos)
        return "Imperva/Incapsula";
      if (lv.find("sucuri_cloudproxy_uuid") != std::string::npos)
        return "Sucuri";
      if (lv.find("__ddg") != std::string::npos) return "DDoS-Guard";
      if (lv.find("datadome=") != std::string::npos) return "DataDome";
    }
  }
  return "";
}

bool looks_like_geo_block(const std::string& body) {
  std::string lb = to_lower(body);
  auto has = [&](const char* s) { return lb.find(s) != std::string::npos; };
  if (has("access from your country is blocked")) return true;
  if (has("access from your region is blocked")) return true;
  if (has("not available in your country")) return true;
  if (has("not available in your region")) return true;
  if (has("service is not available in your location")) return true;
  if (has("blocked due to your location")) return true;
  if (has("geo restriction") || has("geoblock") || has("geo-block")) return true;
  return false;
}

